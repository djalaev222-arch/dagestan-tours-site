export function getTourById(id) {
  return tours.find((tour) => tour.id === id) ?? null
}

export function filterTours({ type, difficulty, region, maxPrice, q } = {}) {
  return tours.filter((tour) => {
    if (type && tour.type !== type) return false
    if (difficulty && tour.difficulty !== difficulty) return false
    if (region && !tour.region.toLowerCase().includes(String(region).toLowerCase())) return false
    if (maxPrice && tour.priceFrom > Number(maxPrice)) return false
    if (q) {
      const query = String(q).toLowerCase()
      if (!tour.title.toLowerCase().includes(query) && !tour.region.toLowerCase().includes(query)) return false
    }
    return true
  })
}
